"""Markdown report for the torsion benchmark results of the mesh levels that were run."""

from collections.abc import Sequence
from enum import Enum

from analytical import AnalyticalSolution, analytical_solution
from benchmark_parameters import FINE, BenchmarkParameters
from runner import ZERO_TWIST_FRACTION, BenchmarkResult

TIP_TWIST_TOLERANCE_PERCENT = 8.0
"""Allowed |error| of φ(L) against the thin-walled Vlasov target. Wider than the stress
tolerance because the thin-walled J overestimates the solid section's torsion constant."""
WARPING_STRESS_TOLERANCE_PERCENT = 5.0


class Verdict(Enum):
    PASS = "PASS"
    FAIL = "FAIL"


def verdict(results: Sequence[BenchmarkResult]) -> Verdict | None:
    """PASS or FAIL from the fine mesh level alone; None when the fine level wasn't run.

    The warping stress errors are signed against signed targets, so a flipped flange-tip sign
    gives about −200 % and fails.
    """
    fine = next((r for r in results if r.mesh_level == FINE), None)
    if fine is None:
        return None
    passed = abs(fine.tip_twist_error) <= TIP_TWIST_TOLERANCE_PERCENT and all(
        abs(e) <= WARPING_STRESS_TOLERANCE_PERCENT for e in fine.warping_stress_errors
    )
    return Verdict.PASS if passed else Verdict.FAIL


def verdict_text(evaluated: Verdict | None) -> str:
    return evaluated.value if evaluated else "not evaluated (fine mesh level not run)"


def render_report(
    results: Sequence[BenchmarkResult], params: BenchmarkParameters, ccx_version: str
) -> str:
    analytical = analytical_solution(params)
    verdict_line = verdict_text(verdict(results))
    lines = [
        "# IPE 200 cantilever in torsion benchmark report",
        "",
        "Generated by `python benchmark.py`. Do not edit by hand.",
        "",
        f"- Solver: CalculiX ccx, {ccx_version}",
        f"- Verdict: **{verdict_line}**",
        "- Figures: [FIGURES.md](FIGURES.md), generated by `python plots.py`",
        "",
        *_parameters_section(params),
        *_targets_section(analytical),
        *_convergence_section(results, analytical),
        "## Verdict",
        "",
        f"**{verdict_line}**. The rule: PASS when the fine mesh level has |error vs Vlasov| ≤ "
        f"{TIP_TWIST_TOLERANCE_PERCENT:g} % on φ(L) and |error| ≤ "
        f"{WARPING_STRESS_TOLERANCE_PERCENT:g} % on the warping stress at each of the four "
        "flange tips at x = L/4, with the + − − + signs. The errors are signed against signed "
        "targets, so a flipped sign gives about −200 % and fails. The coarse and medium levels, "
        "the St-Venant shear and the root peak stress do not affect it.",
        "",
        "## How the values are measured",
        "",
        "- **Twist** φ(x) = (u_z,top − u_z,bottom)/h_m, from the mean u_z of the flange "
        "mid-plane centre nodes (the nodes on each flange mid-plane over the web footprint, "
        "|z| ≤ t_w/2) at each x station, read from the `.frd`. The tip twist is φ(L). A torque "
        "about +x moves the top flange towards +z, so φ is positive.",
        "- **Warping stress** σ_w at each flange-tip edge (z = ±b/2) at x = L/4: the mean nodal "
        "(extrapolated) σ_xx from the `.frd` over the edge's nodes through the flange thickness, "
        "which matches the mid-plane sectorial coordinate of thin-walled theory.",
        "- **Sign pattern.** σ_w = −E·y·z·φ''(x), and φ'' > 0 for T about +x. The top flange "
        "bends laterally towards +z, which compresses its +z edge. So, in the table's order, the "
        "top flange tip at z = −b/2 is in tension (+), the top flange tip at z = +b/2 in "
        "compression (−), the bottom flange tip at z = −b/2 in compression (−) and the bottom "
        "flange tip at z = +b/2 in tension (+): **+ − − +**.",
        "- **St-Venant shear** τ_SV (information) is τ_xz on the flange outer surfaces at "
        "x = L/2, at the centres of the flange outstands (z = ±(b/2 + t_w/2)/2, away from the "
        "web): the mean on the top surface minus the mean on the bottom surface, halved, since "
        "the St-Venant shear is +G·t_f·φ' on the top outer surface and −G·t_f·φ' on the bottom "
        "one. Warping shear from the flanges' lateral bending is mixed in, but at midspan it is "
        "small next to τ_SV. Most of the fine-level gap follows the FE twist rate at midspan, "
        "which is above the Vlasov φ' for the J reason given below. The coarse level's larger "
        "gap comes from its single element through the flange thickness, which resolves the "
        "through-thickness shear poorly.",
        "- **Root peak von Mises** (information) is the largest nodal von Mises stress on the "
        "root face. The fixed face is singular where it meets the free surfaces, so it grows as "
        f"the mesh is refined. Thin-walled theory gives σ_w = {analytical.root_warping_stress:.2f} "
        "MPa at the flange tips there.",
        "- **No reference-node measurement.** ccx reports the `*COUPLING` reference node's "
        "displacement as zero, so the twist is measured on the beam itself.",
        "- **Zero-twist guard.** A run whose |φ(L)| is below "
        f"{ZERO_TWIST_FRACTION:.0%} of φ_SV(L) stops with an error and writes no report, because "
        "the torque did not reach the beam.",
        "- **Load introduction.** The torque goes in through `*COUPLING` + `*DISTRIBUTING` on a "
        "face-based tip surface, not `*DISTRIBUTING COUPLING`, which drops a moment without a "
        "warning in ccx 2.24. See [ADR 0003](../../docs/adr/0003-torsion-coupling.md).",
        "",
        *_theory_gap_section(analytical),
    ]
    return "\n".join(lines)


def _theory_gap_section(a: AnalyticalSolution) -> list[str]:
    j_drop = (1 - a.end_corrected_torsion_constant / a.torsion_constant) * 100
    return [
        "## Expected gap to thin-walled theory",
        "",
        "The targets come from thin-walled formulas, applied here to a solid section, so a few "
        "percent of difference is expected even on a converged mesh. The sources:",
        "",
        "- **No end correction in Σbt³/3.** The thin-walled J ignores the plate ends, where the "
        "shear flow turns round. With the end correction (1 − 0.63·t/b) per plate, J is "
        f"{j_drop:.1f} % lower. The solid is "
        "softer in St-Venant torsion than the target assumes, so it twists more, and with the "
        "smaller λ warping carries more of the torque, which raises σ_w. With the end-corrected "
        f"J, Vlasov gives φ(L) = {a.end_corrected_tip_twist:.5f} rad and σ_w(L/4) = "
        f"{a.end_corrected_quarter_span_warping_stress:.2f} MPa (information). This is the main "
        "cause of the gap.",
        "- **The web-flange junction** adds material and torsional stiffness that the formula "
        "ignores. It works the other way and partly offsets the end correction.",
        "- **No warping shear deformation.** Thin-walled theory takes the flange mid-planes as "
        "shear-rigid in warping; the solid deforms in shear as the flanges bend laterally, "
        "which softens it a little more.",
        "- **The tip load-introduction zone.** The coupling spreads the torque over the tip face "
        "differently from the St-Venant shear flow. The disturbance is local to the tip and "
        "does not reach x = L/4.",
        "",
        "Because the coarse mesh is slightly stiffer in torsion, the errors against the "
        "thin-walled targets grow a little as the mesh is refined, rather than shrink: the FE "
        "converges towards the solid section's answer, which lies near the end-corrected "
        "values, not towards the thin-walled targets.",
        "",
    ]


def _parameters_section(params: BenchmarkParameters) -> list[str]:
    s, m = params.section, params.material
    return [
        "## Benchmark parameters",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Section (IPE 200, no fillet radii) | h = {s.height:g}, b = {s.flange_width:g}, "
        f"t_w = {s.web_thickness:g}, t_f = {s.flange_thickness:g} mm |",
        f"| Length | L = {params.length:g} mm |",
        f"| Material | E = {m.youngs_modulus:g} MPa, ν = {m.poissons_ratio:g} |",
        f"| Load | T = {params.torque:g} N·mm about +x (right-hand rule) at the reference node |",
        "| Support | all degrees of freedom fixed on the root face (x = 0), warping restrained |",
        "| Elements | C3D20R; torque through `*COUPLING` + `*DISTRIBUTING` (DOFs 1–6) on the "
        "tip face, which is free to warp |",
        "",
    ]


def _targets_section(a: AnalyticalSolution) -> list[str]:
    return [
        "## Section properties and targets",
        "",
        "| Quantity | Value |",
        "|---|---|",
        f"| G = E/(2(1+ν)) | {a.shear_modulus:.1f} MPa |",
        f"| J = (2·b·t_f³ + (h − 2t_f)·t_w³)/3 | {a.torsion_constant:.1f} mm⁴ |",
        f"| I_f = t_f·b³/12 | {a.flange_second_moment:.1f} mm⁴ |",
        f"| h_m = h − t_f | {a.flange_mid_plane_distance:g} mm |",
        f"| I_w = I_f·h_m²/2 | {a.warping_constant:.4e} mm⁶ |",
        f"| λ = √(GJ/(E·I_w)) | {a.torsion_parameter:.5e} mm⁻¹ |",
        f"| λL | {a.torsion_parameter_times_length:.4f} |",
        f"| ω = h_m·b/4 at the flange tips | {a.flange_tip_sectorial_coordinate:g} mm² |",
        f"| φ_SV(L) = TL/(GJ) (information) | {a.st_venant_tip_twist:.5f} rad |",
        f"| φ(L), Vlasov (target) | {a.tip_twist:.5f} rad |",
        f"| J, end-corrected (information) | {a.end_corrected_torsion_constant:.1f} mm⁴ |",
        "| φ(L), Vlasov with end-corrected J (information) | "
        f"{a.end_corrected_tip_twist:.5f} rad |",
        f"| σ_w = E·ω·φ''(L/4) at the flange tips (target) | "
        f"{a.quarter_span_warping_stress:.2f} MPa |",
        "| σ_w(L/4), Vlasov with end-corrected J (information) | "
        f"{a.end_corrected_quarter_span_warping_stress:.2f} MPa |",
        f"| σ_w at the root (information) | {a.root_warping_stress:.2f} MPa |",
        f"| τ_SV = G·t_f·φ'(L/2) at the flange surface (information) | "
        f"{a.midspan_st_venant_shear_stress:.2f} MPa |",
        "",
    ]


def _convergence_section(
    results: Sequence[BenchmarkResult], analytical: AnalyticalSolution
) -> list[str]:
    lines = [
        "## Convergence",
        "",
        "Error = (FE − analytical) / analytical × 100, signed. The warping stresses σ_w are at "
        "the flange tips at x = L/4, against the signed targets "
        + ", ".join(f"{t:+.2f}" for t in analytical.quarter_span_flange_tip_warping_stresses)
        + " MPa. τ_SV and the root peak are for information only.",
        "",
        "| Mesh level | Elements | Nodes | φ(L) (rad) | Error vs Vlasov (%) "
        "| Error vs St-Venant (%) | σ_w top −z (MPa) | Error (%) | σ_w top +z (MPa) | Error (%) "
        "| σ_w bottom −z (MPa) | Error (%) | σ_w bottom +z (MPa) | Error (%) "
        "| τ_SV at L/2 (MPa) | Error (%) | Root peak von Mises (MPa) |",
        "|---|" + "---:|" * 16,
    ]
    for r in results:
        stresses = "".join(
            f"| {value:+.2f} | {error:+.2f} "
            for value, error in zip(
                r.flange_tip_warping_stresses, r.warping_stress_errors, strict=True
            )
        )
        lines.append(
            f"| {r.mesh_level.name} | {r.element_count} | {r.node_count} "
            f"| {r.tip_twist:.5f} | {r.tip_twist_error:+.2f} | {r.st_venant_tip_twist_error:+.2f} "
            f"{stresses}| {r.midspan_st_venant_shear_stress:.2f} "
            f"| {r.st_venant_shear_stress_error:+.2f} | {r.root_peak_von_mises:.2f} |"
        )
    levels = ", ".join(r.mesh_level.label for r in results)
    lines += [
        "",
        "Mesh levels, as elements through the flange thickness / along the web height / along "
        f"the length: {levels}. Node counts include the reference node.",
        "",
    ]
    return lines
