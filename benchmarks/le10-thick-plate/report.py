"""Markdown report for the LE10 benchmark results of the mesh levels that were run."""

from collections.abc import Sequence

from benchmark_parameters import BenchmarkParameters
from reference import quarter_annulus_volume, target_stress_at_d, top_face_area
from runner import BenchmarkResult

VERDICT_TEXT = "not evaluated (the verdict rule is not implemented yet)"
ADR = "[ADR 0004](../../docs/adr/0004-published-reference-value.md)"


def render_report(
    results: Sequence[BenchmarkResult], params: BenchmarkParameters, ccx_version: str
) -> str:
    lines = [
        "# NAFEMS LE10 thick plate benchmark report",
        "",
        "Generated by `python benchmark.py`. Do not edit by hand.",
        "",
        f"- Solver: CalculiX ccx, {ccx_version}",
        f"- Verdict: **{VERDICT_TEXT}**",
        "- Figures: [FIGURES.md](FIGURES.md), generated by `python plots.py`",
        "",
        *_parameters_section(params),
        *_target_section(params),
        *_levels_section(results),
        *_stress_at_d_section(results),
        "## How the values are measured",
        "",
        "- **σ_yy(D)** is ccx's nodal σ_yy at point D, read from the `.frd`: ccx extrapolates "
        "the integration-point stresses of each element to its nodes and averages them over "
        "the elements that share the node. At D only one element does.",
        "- **Integration point** is the integration point of that element nearest D, printed "
        "to the `.dat` with `*EL PRINT`. It shows how much of the nodal value comes from "
        "extrapolation.",
        "",
    ]
    return "\n".join(lines)


def _parameters_section(params: BenchmarkParameters) -> list[str]:
    inner, outer, m = params.inner, params.outer, params.material
    half = params.thickness / 2
    return [
        "## Benchmark parameters",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Inner ellipse (hole edge) | a_i = {inner.semi_axis_x:g}, "
        f"b_i = {inner.semi_axis_y:g} mm |",
        f"| Outer ellipse | a_o = {outer.semi_axis_x:g}, b_o = {outer.semi_axis_y:g} mm |",
        f"| Thickness | t = {params.thickness:g} mm, z from −{half:g} to +{half:g} mm |",
        f"| Material | E = {m.youngs_modulus:g} MPa, ν = {m.poissons_ratio:g} |",
        f"| Load | p = {params.pressure:g} MPa on the top face (z = +{half:g} mm) |",
        "| Supports | u_y = 0 on y = 0; u_x = 0 on x = 0; u_x = u_y = 0 on the outer face; "
        "u_z = 0 on line EE′ (the outer face at z = 0) |",
        "| Elements | C3D20R, mapped mesh, midside nodes on the ellipses |",
        f"| Top-face area (π/4)(a_o·b_o − a_i·b_i) | {top_face_area(params):.1f} mm² |",
        f"| Volume | {quarter_annulus_volume(params):.5e} mm³ |",
        "",
    ]


def _target_section(params: BenchmarkParameters) -> list[str]:
    half = params.thickness / 2
    return [
        "## Target",
        "",
        "| Quantity | Value |",
        "|---|---|",
        f"| σ_yy(D), published (target) | {_minus(target_stress_at_d())} MPa |",
        "",
        f"Point D is (a_i, 0, +{half:g}) mm: on the hole edge, on the x axis, on the loaded "
        "face. The value is the NAFEMS LE10 reference as published in four vendor "
        "verification documents that agree on it: the Abaqus Benchmarks Manual, Altair "
        "OptiStruct, Seamplex/Fino case 012 and the COMSOL thick_plate model. The primary "
        "NAFEMS document, TNSB Rev. 3, was not consulted. It is compressive; some sources "
        f"quote the magnitude 5.38 MPa. See {ADR}.",
        "",
    ]


def _levels_section(results: Sequence[BenchmarkResult]) -> list[str]:
    lines = [
        "## Mesh levels",
        "",
        "Error = (FE − target) / target × 100, signed, so a flipped sign gives about −200 %.",
        "",
        "| Mesh level | Elements | Nodes | σ_yy(D) (MPa) | Error (%) "
        "| Integration point σ_yy (MPa) |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    lines += [
        f"| {r.mesh_level.label} | {r.element_count} | {r.node_count} "
        f"| {r.stress_yy_at_d:.3f} | {r.stress_yy_at_d_error:+.2f} "
        f"| {r.integration_point_stress_yy_at_d:.3f} |"
        for r in results
    ]
    lines += [
        "",
        "Mesh levels are counted as elements around the annulus × across it × through the "
        "thickness.",
        "",
    ]
    return lines


def _stress_at_d_section(results: Sequence[BenchmarkResult]) -> list[str]:
    lines = [
        "## Stress at D",
        "",
        "Nodal stress tensor and von Mises stress at D, in MPa. The plate's stress state is "
        "fully three-dimensional, but D's exact state is biaxial: D lies on the traction-free "
        "hole surface (normal −x) and on the loaded top face, so σ_xx = τ_xy = τ_yz = τ_zx = 0 "
        "and σ_zz = −p there. How far the FE values are from that is a check on the surface "
        "tractions.",
        "",
        "| Mesh level | σ_xx | σ_yy | σ_zz | τ_xy | τ_yz | τ_zx | von Mises |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in results:
        components = " | ".join(f"{s:.3f}" for s in r.stress_at_d)
        lines.append(f"| {r.mesh_level.name} | {components} | {r.von_mises_at_d:.3f} |")
    lines.append("")
    return lines


def _minus(value: float) -> str:
    return f"{value:g}".replace("-", "−")
