"""Verdict and markdown report for the benchmark results of all mesh levels."""

import math
from collections.abc import Sequence
from enum import Enum
from itertools import pairwise

from analytical import AnalyticalSolution, analytical_solution, bending_stress_at
from benchmark_parameters import FINE, MESH_LEVELS, BenchmarkParameters
from runner import BenchmarkResult

TOLERANCE_PERCENT = 1.0


class Verdict(Enum):
    PASS = "PASS"
    FAIL = "FAIL"


def verdict(results: Sequence[BenchmarkResult]) -> Verdict | None:
    """PASS or FAIL; None unless the coarse, medium and fine levels were all run, because the
    shrink condition needs all three."""
    by_level = {r.mesh_level: r for r in results}
    if any(level not in by_level for level in MESH_LEVELS):
        return None
    levels = [by_level[level] for level in MESH_LEVELS]
    passed = _fine_within_tolerance(by_level[FINE]) and _stress_error_shrinks(levels)
    return Verdict.PASS if passed else Verdict.FAIL


def observed_order(errors: Sequence[float]) -> float | None:
    """p = ln((e_c − e_m)/(e_m − e_f)) / ln 2 from the signed coarse, medium and fine errors;
    None without all three or when the ratio is not positive."""
    if len(errors) != 3:
        return None
    coarse, medium, fine = errors
    if medium == fine:
        return None
    ratio = (coarse - medium) / (medium - fine)
    return math.log(ratio) / math.log(2) if ratio > 0 else None


def _fine_within_tolerance(fine: BenchmarkResult) -> bool:
    errors = (
        fine.deflection_error,
        fine.midspan_top_stress_error,
        fine.midspan_bottom_stress_error,
    )
    return all(abs(e) <= TOLERANCE_PERCENT for e in errors)


def _stress_error_shrinks(levels: Sequence[BenchmarkResult]) -> bool:
    """The fitted stress error magnitude strictly decreases at every refinement, at both fibres."""
    for name in ("midspan_top_stress_error", "midspan_bottom_stress_error"):
        magnitudes = [abs(getattr(r, name)) for r in levels]
        if not all(finer < coarser for coarser, finer in pairwise(magnitudes)):
            return False
    return True


def verdict_text(evaluated: Verdict | None) -> str:
    if evaluated:
        return evaluated.value
    return "not evaluated (needs the coarse, medium and fine mesh levels)"


def render_report(
    results: Sequence[BenchmarkResult], params: BenchmarkParameters, ccx_version: str
) -> str:
    analytical = analytical_solution(params)
    verdict_line = verdict_text(verdict(results))
    shear_share = (
        analytical.timoshenko_deflection / analytical.euler_bernoulli_deflection - 1
    ) * 100
    root_bending = bending_stress_at(params, 0.0, analytical.outer_fibre_distance)
    lines = [
        "# CHS 168.3 × 8 tube cantilever benchmark report",
        "",
        "Generated by `python benchmark.py`. Do not edit by hand.",
        "",
        f"- Solver: CalculiX ccx, {ccx_version}",
        f"- Verdict: **{verdict_line}**",
        "- Figures: [FIGURES.md](FIGURES.md), generated by `python plots.py`",
        "",
        *_parameters_section(params),
        *_targets_section(analytical),
        *_convergence_section(results),
        *_observed_order_section(results),
        "## Verdict",
        "",
        f"**{verdict_line}**. The rule: PASS when the fine mesh level has |error vs δ_T| ≤ "
        f"{TOLERANCE_PERCENT:g} % and |midspan stress fit error| ≤ {TOLERANCE_PERCENT:g} % at "
        "both fibres, **and** the midspan stress fit error magnitude strictly decreases coarse → "
        "medium → fine at both fibres. The deflection is not part of the shrink condition, "
        "because it sits on its modelling floor from the medium level on. The single-node "
        "stresses, the information-only deflections and the root peak stress do not affect it. "
        "Without all three levels there is no verdict.",
        "",
        "## How the values are measured",
        "",
        "- **Tip deflection** is u_y at the reference node, read from the `.dat` file "
        "(`*NODE PRINT`), because ccx does not write the reference node to the `.frd`. The "
        "tip-face mean deflection (mean u_y of all tip-face nodes, from the `.frd`) is shown "
        "alongside as a check on the coupling; the tube has no material at its centroid, so "
        "there is no centreline node to compare with.",
        "- **Deflection floor.** From the medium level on, the deflection error sits at about "
        "−0.007 % against δ_T. That is a modelling residual, the difference between the clamped "
        "solid loaded through a distributing coupling and Timoshenko beam theory, at the "
        "resolution of the `.dat` print. It is not mesh error, so the deflection's observed "
        "order is not defined.",
        "- **Midspan stress fit** is the least-squares fit σ_xx = a·y + b over every "
        "outer-surface node at x = L/2 (corner and midside), using the nodal (extrapolated) "
        "σ_xx from the `.frd`. It gives a·r_o + b at the top fibre and −a·r_o + b at the "
        "bottom fibre, so the intercept b lets the two fibres differ and each is checked "
        "against the tolerance on its own.",
        "- **Single-node stresses** are the nodal σ_xx at the top-fibre (y = r_o) and "
        "bottom-fibre (y = −r_o) nodes at x = L/2, shown next to the fit for comparison.",
        "- **Signs.** The −y tip load gives a hogging moment along the cantilever, so the top "
        "fibre is in tension (+) and the bottom fibre in compression (−). Stress errors keep "
        "their sign, so a flipped sign shows as about −200 % and fails.",
        "- **Section discretisation error.** The targets use the exact annulus, while the mesh "
        "approximates the circle with quadratic arcs, so the stress error falls as the "
        "circumferential divisions grow.",
        "- **Shear.** With Cowper's κ, shear adds "
        f"{shear_share:.1f} % to the Euler-Bernoulli deflection. The errors against "
        "Euler-Bernoulli and against the thin-wall κ = 0.5 are shown for information, to show "
        "that the FE result tells them apart.",
        "- **Root peak von Mises** is the largest nodal von Mises stress on the root face. It is "
        "for information only, because the fixed end disturbs it (St-Venant). Beam theory gives "
        f"P·L·r_o/I = {root_bending:.2f} MPa there.",
        "- **Observed order** p = ln((e_c − e_m)/(e_m − e_f)) / ln 2 from the signed errors of "
        "the three levels, for information. It is n/a when the ratio is not positive or a level "
        "is missing.",
        "",
    ]
    return "\n".join(lines)


def _parameters_section(params: BenchmarkParameters) -> list[str]:
    s, m = params.section, params.material
    return [
        "## Benchmark parameters",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Section (EN 10210 CHS 168.3 × 8) | r_o = {s.outer_radius:g}, t = "
        f"{s.wall_thickness:g}, r_i = {s.inner_radius:g} mm |",
        f"| Length | L = {params.length:g} mm |",
        f"| Material | E = {m.youngs_modulus:g} MPa, ν = {m.poissons_ratio:g} |",
        f"| Load | P = {params.tip_load:g} N in −y at the reference node |",
        "| Support | all degrees of freedom fixed on the root face (x = 0) |",
        "| Elements | C3D20R; tip load through `*DISTRIBUTING COUPLING` to the reference node |",
        "",
    ]


def _targets_section(a: AnalyticalSolution) -> list[str]:
    return [
        "## Section properties and targets",
        "",
        "| Quantity | Value |",
        "|---|---|",
        f"| A = π(r_o² − r_i²) | {a.area:.2f} mm² |",
        f"| I = π(r_o⁴ − r_i⁴)/4 | {a.second_moment_of_area:.1f} mm⁴ |",
        f"| κ (Cowper) | {a.shear_coefficient:.4f} |",
        f"| r_o | {a.outer_fibre_distance:g} mm |",
        f"| G | {a.shear_modulus:.1f} MPa |",
        f"| δ_EB = PL³/(3EI) (information) | {a.euler_bernoulli_deflection:.5f} mm |",
        f"| δ_T = δ_EB + PL/(κ·G·A), Cowper κ (target) | {a.timoshenko_deflection:.5f} mm |",
        f"| δ with thin-wall κ = 0.5 (information) | {a.thin_wall_timoshenko_deflection:.5f} mm |",
        f"| σ = P·(L/2)·r_o/I at midspan (target) | {a.midspan_stress:.4f} MPa |",
        "",
    ]


def _convergence_section(results: Sequence[BenchmarkResult]) -> list[str]:
    lines = [
        "## Convergence",
        "",
        "Deflections are magnitudes of u_y; stresses keep their sign. "
        "Error = (FE − analytical) / analytical × 100. Deflection errors use magnitudes. Stress "
        "errors are signed, against +σ at the top fibre and −σ at the bottom fibre.",
        "",
        "| Mesh level | Elements | Nodes | δ ref node (mm) | δ tip-face mean (mm) "
        "| Error vs δ_T (%) | Error vs κ = 0.5 (%) | Error vs EB (%) "
        "| σ fit top (MPa) | Error (%) | σ fit bottom (MPa) | Error (%) "
        "| σ top node (MPa) | Error (%) | σ bottom node (MPa) | Error (%) "
        "| Root peak von Mises (MPa) |",
        "|---|" + "---:|" * 16,
    ]
    for r in results:
        lines.append(
            f"| {r.mesh_level.name} | {r.element_count} | {r.node_count} "
            f"| {abs(r.reference_node_uy):.5f} | {abs(r.tip_face_mean_uy):.5f} "
            f"| {r.deflection_error:+.3f} | {r.thin_wall_deflection_error:+.3f} "
            f"| {r.euler_bernoulli_deflection_error:+.2f} "
            f"| {r.midspan_top_fitted_sxx:+.4f} | {r.midspan_top_stress_error:+.3f} "
            f"| {r.midspan_bottom_fitted_sxx:+.4f} | {r.midspan_bottom_stress_error:+.3f} "
            f"| {r.top_fibre_sxx:+.4f} | {r.top_fibre_stress_error:+.3f} "
            f"| {r.bottom_fibre_sxx:+.4f} | {r.bottom_fibre_stress_error:+.3f} "
            f"| {r.root_peak_von_mises:.2f} |"
        )
    levels = ", ".join(r.mesh_level.label for r in results)
    lines += [
        "",
        "Mesh levels, as elements around the circumference / through the wall / along the "
        f"length: {levels}. Node counts include the reference node.",
        "",
    ]
    return lines


def _observed_order_section(results: Sequence[BenchmarkResult]) -> list[str]:
    by_level = {r.mesh_level: r for r in results}
    ordered = [by_level[level] for level in MESH_LEVELS if level in by_level]
    quantities = [
        ("Deflection vs δ_T", "deflection_error"),
        ("Midspan stress fit, top fibre", "midspan_top_stress_error"),
        ("Midspan stress fit, bottom fibre", "midspan_bottom_stress_error"),
        ("Single-node stress, top fibre", "top_fibre_stress_error"),
        ("Single-node stress, bottom fibre", "bottom_fibre_stress_error"),
    ]
    lines = [
        "## Observed order",
        "",
        "For information; it does not affect the verdict.",
        "",
        "| Quantity | Observed order p |",
        "|---|---:|",
    ]
    for label, name in quantities:
        order = observed_order([getattr(r, name) for r in ordered])
        lines.append(f"| {label} | {'n/a' if order is None else f'{order:.2f}'} |")
    return [*lines, ""]
