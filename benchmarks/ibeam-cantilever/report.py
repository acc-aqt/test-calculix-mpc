"""Verdict and markdown report for the benchmark results of all mesh levels."""

from collections.abc import Sequence
from enum import Enum

from benchmark_parameters import FINE, BenchmarkParameters
from runner import BenchmarkResult

TOLERANCE_PERCENT = 2.0


class Verdict(Enum):
    PASS = "PASS"
    FAIL = "FAIL"


def verdict(results: Sequence[BenchmarkResult]) -> Verdict | None:
    """PASS or FAIL from the fine mesh level alone; None when the fine level wasn't run."""
    fine = next((r for r in results if r.mesh_level == FINE), None)
    if fine is None:
        return None
    errors = (
        fine.deflection_error,
        fine.midspan_top_stress_error,
        fine.midspan_bottom_stress_error,
    )
    passed = all(abs(e) <= TOLERANCE_PERCENT for e in errors)
    return Verdict.PASS if passed else Verdict.FAIL


def verdict_text(evaluated: Verdict | None) -> str:
    return evaluated.value if evaluated else "not evaluated (fine mesh level not run)"


def render_report(
    results: Sequence[BenchmarkResult], params: BenchmarkParameters, ccx_version: str
) -> str:
    a = results[0].analytical
    verdict_line = verdict_text(verdict(results))
    shear_share = (a.timoshenko_deflection / a.euler_bernoulli_deflection - 1) * 100
    lines = [
        "# IPE 200 cantilever benchmark report",
        "",
        "Generated by `python benchmark.py`. Do not edit by hand.",
        "",
        f"- Solver: CalculiX ccx, {ccx_version}",
        f"- Verdict: **{verdict_line}**",
        "",
        *_parameters_section(params),
        *_targets_section(results[0]),
        *_convergence_section(results),
        "## Verdict",
        "",
        f"**{verdict_line}**. The rule: PASS when the fine mesh has |error vs Timoshenko| ≤ "
        f"{TOLERANCE_PERCENT:g} % and |midspan σ_xx error| ≤ {TOLERANCE_PERCENT:g} % at both "
        "flanges. The coarse and medium levels and the root peak stress do not affect it.",
        "",
        "## How the values are measured",
        "",
        "- **Tip deflection** is u_y at the reference node, read from the `.dat` file "
        "(`*NODE PRINT`), because ccx does not write the reference node to the `.frd`. The "
        "web-centreline tip node (from the `.frd`) is shown alongside as a check on the coupling.",
        "- **Midspan σ_xx** is the nodal (extrapolated) stress from the `.frd`, averaged over all "
        "nodes on the outer flange surface at x = L/2 across the full flange width, as the spec's "
        "Further Notes allow.",
        "- **Signs.** The −y tip load gives a hogging moment along the cantilever, so the top "
        "flange is in tension (+) and the bottom flange in compression (−). Spec #1 says the top "
        "flange is compressive. That is a sign slip in the spec; the values here are as computed.",
        "- **Root peak von Mises** is the largest nodal von Mises stress on the root face. It is "
        "for information only, because the fixed end disturbs it (St-Venant). Beam theory gives "
        f"P·L·c/I = {2 * a.midspan_stress:.2f} MPa there. It grows with refinement, as expected at "
        "the stress singularity where the fixed face meets the free surfaces.",
        "- **Spec figures.** Spec #1 quotes I ≈ 1.943×10⁷ mm⁴, δ_EB ≈ 22.06 mm and a shear "
        "contribution of about 5 %. Those belong to the rolled section with fillet radii. The "
        "no-fillet section modelled here gives the values above, and shear adds about "
        f"{shear_share:.1f} %.",
        "",
    ]
    return "\n".join(lines)


def _parameters_section(params: BenchmarkParameters) -> list[str]:
    s, m = params.section, params.material
    return [
        "## Benchmark parameters",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Section (no fillet radii) | h = {s.height:g}, b = {s.flange_width:g}, "
        f"t_w = {s.web_thickness:g}, t_f = {s.flange_thickness:g} mm |",
        f"| Length | L = {params.length:g} mm |",
        f"| Material | E = {m.youngs_modulus:g} MPa, ν = {m.poissons_ratio:g} |",
        f"| Load | P = {params.tip_load:g} N in −y at the reference node |",
        "| Support | all degrees of freedom fixed on the root face (x = 0) |",
        "| Elements | C3D20R; tip load through `*DISTRIBUTING COUPLING` to the reference node |",
        "",
    ]


def _targets_section(result: BenchmarkResult) -> list[str]:
    a = result.analytical
    return [
        "## Section properties and targets",
        "",
        "| Quantity | Value |",
        "|---|---|",
        f"| A | {a.area:.1f} mm² |",
        f"| I | {a.second_moment_of_area:.1f} mm⁴ |",
        f"| A_s = (h − t_f)·t_w, κ = 1 | {a.shear_area:.1f} mm² |",
        f"| c = h/2 | {a.outer_fibre_distance:g} mm |",
        f"| G | {a.shear_modulus:.1f} MPa |",
        f"| δ_EB = PL³/(3EI) (information) | {a.euler_bernoulli_deflection:.4f} mm |",
        f"| δ_T = δ_EB + PL/(κ·G·A_s) (target) | {a.timoshenko_deflection:.4f} mm |",
        f"| σ = P·(L/2)·c/I at midspan (target) | {a.midspan_stress:.4f} MPa |",
        "",
    ]


def _convergence_section(results: Sequence[BenchmarkResult]) -> list[str]:
    lines = [
        "## Convergence",
        "",
        "Deflections are magnitudes of u_y; stresses keep their sign. "
        "Error = (FE − analytical) / analytical × 100. Deflection errors use magnitudes. Stress "
        "errors are signed, against +σ at the top flange and −σ at the bottom flange.",
        "",
        "| Mesh level | Elements | Nodes | δ ref node (mm) | δ web tip (mm) | Error vs EB (%) "
        "| Error vs Timoshenko (%) | σ_xx top (MPa) | Error (%) | σ_xx bottom (MPa) | Error (%) "
        "| Root peak von Mises (MPa) |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in results:
        lines.append(
            f"| {r.mesh_level.name} | {r.element_count} | {r.node_count} "
            f"| {abs(r.reference_node_uy):.4f} | {abs(r.web_centreline_tip_uy):.4f} "
            f"| {r.euler_bernoulli_deflection_error:+.3f} | {r.deflection_error:+.3f} "
            f"| {r.midspan_top_sxx_width_mean:+.4f} | {r.midspan_top_stress_error:+.3f} "
            f"| {r.midspan_bottom_sxx_width_mean:+.4f} | {r.midspan_bottom_stress_error:+.3f} "
            f"| {r.root_peak_von_mises:.2f} |"
        )
    levels = ", ".join(
        f"{r.mesh_level.name} {r.mesh_level.flange_thickness_divisions}/"
        f"{r.mesh_level.web_height_divisions}/{r.mesh_level.length_divisions}"
        for r in results
    )
    lines += [
        "",
        "Mesh levels, as elements through the flange thickness / along the web height / along "
        f"the length: {levels}. Node counts include the reference node.",
        "",
    ]
    return lines
